"""Structural validation for luminumbra.game.resource-accounting.v1 files.

The files are generated by tools/check_tree_small_02_receipts.py. This module
checks shape and internal consistency only; it does not re-derive values from a
conversion receipt. Every measured entry must carry an evidence_sha256 identity.

Every field is type-checked before it is used, so malformed input produces a
"PATH: reason" problem rather than an exception.
"""

import re

from lumlib import schema
from lumlib.schema import SchemaError

SCHEMA = "luminumbra.game.resource-accounting.v1"

_HEX40 = re.compile(r"[0-9a-f]{40}")
_HEX64 = re.compile(r"[0-9a-f]{64}")

_WINDOWS_RESERVED = frozenset(
    ["CON", "PRN", "AUX", "NUL"]
    + ["COM%d" % number for number in range(1, 10)]
    + ["LPT%d" % number for number in range(1, 10)]
)
_WINDOWS_INVALID_CHARS = frozenset('<>:"|?*')

_TOP_KEYS = {
    "schema",
    "asset",
    "scope",
    "engine_revision",
    "source_receipt",
    "meshes",
    "textures",
    "totals",
    "measured",
    "notes",
}
_SOURCE_KEYS = {"schema", "sha256"}
_MESH_KEYS = {
    "path",
    "lod",
    "part",
    "vertices",
    "triangles",
    "vertex_bytes",
    "index_bytes",
    "header_bytes",
    "file_bytes",
    "basis",
}
_TEXTURE_KEYS = {"path", "file_bytes", "header_bytes", "payload_bytes", "basis"}
_TOTAL_KEYS = {
    "mesh_file_bytes",
    "mesh_triangles_by_lod",
    "texture_file_bytes",
    "texture_payload_bytes",
    "leaf_surfaces",
}
_LOD_KEYS = {"lod0", "lod1", "lod2"}
_MEASURED_REQUIRED = {"evidence_sha256"}
_MEASURED_OPTIONAL = {"metric", "value", "path", "unit"}

_MESH_HEADER = 28
_VERTEX_BYTES = 32
_INDEX_BYTES = 12
_TEXTURE_HEADER = 17
_TEXTURE_PAYLOAD = sum(max(1, 512 >> m) ** 2 * 4 for m in range(10))
_PARTS = ("branches", "leaves", "trunk")
_LODS = (0, 1, 2)
_TOTAL_INT_KEYS = ("mesh_file_bytes", "texture_file_bytes", "texture_payload_bytes", "leaf_surfaces")


def _is_int(value):
    return isinstance(value, int) and not isinstance(value, bool)


def _is_sha(value, pattern):
    return isinstance(value, str) and pattern.fullmatch(value) is not None


def _path_problem(value):
    """Return a reason the value is not a portable Windows-safe relative path, or None."""
    if not isinstance(value, str) or not value:
        return "must be a non-empty string"
    if "\\" in value:
        return "must not contain a backslash"
    if value.startswith("/"):
        return "must not start with a slash"
    segments = value.split("/")
    if any(segment in ("", ".", "..") for segment in segments):
        return "must not contain empty, '.' or '..' segments"
    if any(char in _WINDOWS_INVALID_CHARS or ord(char) < 32 or ord(char) == 127 for char in value):
        return "must not contain characters invalid on Windows or control characters"
    for segment in segments:
        if segment.endswith(".") or segment.endswith(" "):
            return "must not end a component with a dot or space (%r)" % segment
    for segment in segments:
        stem = segment.split(".", 1)[0].casefold()
        if stem.upper() in _WINDOWS_RESERVED:
            return "must not use the Windows reserved device name %r" % segment
    return None


def _validate_mesh(label, index, row, problems):
    where = "%s: meshes[%d]" % (label, index)
    try:
        schema.check_keys(row, _MESH_KEYS, set(), where)
    except SchemaError as exc:
        problems.append(str(exc))
        return None
    path_problem = _path_problem(row["path"])
    if path_problem is not None:
        problems.append("%s: path %s" % (where, path_problem))
    if not isinstance(row["part"], str) or row["part"] not in _PARTS:
        problems.append("%s: unknown part %r" % (where, row["part"]))
    if not _is_int(row["lod"]) or row["lod"] not in _LODS:
        problems.append("%s: lod must be 0, 1 or 2" % where)
    for key in ("vertices", "triangles", "vertex_bytes", "index_bytes", "header_bytes", "file_bytes"):
        if not _is_int(row[key]) or row[key] < 0:
            problems.append("%s: %s must be a non-negative integer" % (where, key))
            return None
    if row["header_bytes"] != _MESH_HEADER:
        problems.append("%s: header_bytes must be %d" % (where, _MESH_HEADER))
    if row["vertex_bytes"] != _VERTEX_BYTES * row["vertices"]:
        problems.append("%s: vertex_bytes must be 32 * vertices" % where)
    if row["index_bytes"] != _INDEX_BYTES * row["triangles"]:
        problems.append("%s: index_bytes must be 12 * triangles" % where)
    expected = _MESH_HEADER + row["vertex_bytes"] + row["index_bytes"]
    if row["file_bytes"] != expected:
        problems.append("%s: file_bytes must be %d" % (where, expected))
    if row["basis"] != "estimated":
        problems.append("%s: basis must be 'estimated'" % where)
    return row


def _validate_texture(label, index, row, problems):
    where = "%s: textures[%d]" % (label, index)
    try:
        schema.check_keys(row, _TEXTURE_KEYS, set(), where)
    except SchemaError as exc:
        problems.append(str(exc))
        return None
    path_problem = _path_problem(row["path"])
    if path_problem is not None:
        problems.append("%s: path %s" % (where, path_problem))
    for key in ("file_bytes", "header_bytes", "payload_bytes"):
        if not _is_int(row[key]) or row[key] < 0:
            problems.append("%s: %s must be a non-negative integer" % (where, key))
            return None
    if row["header_bytes"] != _TEXTURE_HEADER:
        problems.append("%s: header_bytes must be %d" % (where, _TEXTURE_HEADER))
    if row["payload_bytes"] != _TEXTURE_PAYLOAD:
        problems.append("%s: payload_bytes must be %d" % (where, _TEXTURE_PAYLOAD))
    if row["file_bytes"] != row["header_bytes"] + row["payload_bytes"]:
        problems.append("%s: file_bytes must equal header_bytes + payload_bytes" % where)
    if row["basis"] != "estimated":
        problems.append("%s: basis must be 'estimated'" % where)
    return row


def _validate_totals(label, totals, meshes, textures, problems):
    where = "%s: totals" % label
    try:
        schema.check_keys(totals, _TOTAL_KEYS, set(), where)
    except SchemaError as exc:
        problems.append(str(exc))
        return
    for key in _TOTAL_INT_KEYS:
        if not _is_int(totals[key]):
            problems.append("%s: %s must be an integer" % (where, key))
    mesh_file = sum(m["file_bytes"] for m in meshes)
    if _is_int(totals["mesh_file_bytes"]) and totals["mesh_file_bytes"] != mesh_file:
        problems.append("%s: mesh_file_bytes %r does not match sum %d" % (where, totals["mesh_file_bytes"], mesh_file))
    by_lod = totals["mesh_triangles_by_lod"]
    try:
        schema.check_keys(by_lod, _LOD_KEYS, set(), where + ".mesh_triangles_by_lod")
    except SchemaError as exc:
        problems.append(str(exc))
    else:
        for lod in _LODS:
            value = by_lod["lod%d" % lod]
            if not _is_int(value):
                problems.append("%s: lod%d triangles must be an integer" % (where, lod))
                continue
            expected = sum(m["triangles"] for m in meshes if m["lod"] == lod)
            if value != expected:
                problems.append("%s: lod%d triangles %r does not match sum %d" % (where, lod, value, expected))
    tex_file = sum(t["file_bytes"] for t in textures)
    if _is_int(totals["texture_file_bytes"]) and totals["texture_file_bytes"] != tex_file:
        problems.append("%s: texture_file_bytes %r does not match sum %d" % (where, totals["texture_file_bytes"], tex_file))
    tex_payload = sum(t["payload_bytes"] for t in textures)
    if _is_int(totals["texture_payload_bytes"]) and totals["texture_payload_bytes"] != tex_payload:
        problems.append(
            "%s: texture_payload_bytes %r does not match sum %d" % (where, totals["texture_payload_bytes"], tex_payload)
        )


def validate_measured(label, measured, problems):
    if not isinstance(measured, list):
        problems.append("%s: measured must be a list" % label)
        return
    for index, entry in enumerate(measured):
        where = "%s: measured[%d]" % (label, index)
        if not isinstance(entry, dict):
            problems.append("%s: not an object" % where)
            continue
        for key in sorted(_MEASURED_REQUIRED):
            if key not in entry:
                problems.append("%s: missing key '%s'" % (where, key))
        unknown = set(entry) - _MEASURED_REQUIRED - _MEASURED_OPTIONAL
        for key in sorted(unknown):
            problems.append("%s: unknown key '%s'" % (where, key))
        if "evidence_sha256" in entry and not _is_sha(entry["evidence_sha256"], _HEX64):
            problems.append("%s: evidence_sha256 must be 64 lowercase hex digits" % where)
        for key in ("metric", "path", "unit"):
            if key in entry and not isinstance(entry[key], str):
                problems.append("%s: %s must be a string" % (where, key))
        if "value" in entry and not _is_int(entry["value"]):
            problems.append("%s: value must be an integer" % where)


def validate(path, obj, ctx=None):
    """Return a list of "PATH: reason" problems for a parsed accounting object."""
    problems = []
    try:
        schema.check_schema_id(obj, SCHEMA, path)
        schema.check_keys(obj, _TOP_KEYS, set(), path)
    except SchemaError as exc:
        return [str(exc)]

    if not _is_sha(obj["engine_revision"], _HEX40):
        problems.append("%s: engine_revision must be 40 lowercase hex digits" % path)
    if not isinstance(obj["asset"], str) or not obj["asset"]:
        problems.append("%s: asset must be a non-empty string" % path)

    source = obj["source_receipt"]
    try:
        schema.check_keys(source, _SOURCE_KEYS, set(), path + ": source_receipt")
    except SchemaError as exc:
        problems.append(str(exc))
    else:
        if source["schema"] != "luminumbra.game.asset-conversion.v1":
            problems.append("%s: source_receipt.schema must be the asset-conversion receipt id" % path)
        if source["sha256"] is not None and not _is_sha(source["sha256"], _HEX64):
            problems.append("%s: source_receipt.sha256 must be null or 64 lowercase hex digits" % path)

    meshes = []
    if not isinstance(obj["meshes"], list):
        problems.append("%s: meshes must be a list" % path)
    else:
        for index, row in enumerate(obj["meshes"]):
            checked = _validate_mesh(path, index, row, problems)
            if checked is not None:
                meshes.append(checked)

    textures = []
    if not isinstance(obj["textures"], list):
        problems.append("%s: textures must be a list" % path)
    else:
        for index, row in enumerate(obj["textures"]):
            checked = _validate_texture(path, index, row, problems)
            if checked is not None:
                textures.append(checked)

    seen = set()
    for row in meshes + textures:
        row_path = row["path"]
        if not isinstance(row_path, str):
            continue
        key = row_path.casefold()
        if key in seen:
            problems.append("%s: duplicate path %s (paths are compared case-insensitively)" % (path, row_path))
        seen.add(key)

    _validate_totals(path, obj["totals"], meshes, textures, problems)
    validate_measured(path, obj["measured"], problems)

    if not isinstance(obj["notes"], list) or not all(isinstance(note, str) for note in obj["notes"]):
        problems.append("%s: notes must be a list of strings" % path)
    return problems


SCHEMAS = {SCHEMA: validate}
